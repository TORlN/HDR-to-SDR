"""Golden master for construct_ffmpeg_command / src.ffmpeg_command.build()
(tech-debt-audit-2026-08-02.md item 6).

RULES FOR EDITING THIS FILE:

1. This file changes only as its own commit, never bundled with a feature
   commit. Feature work must make it fail first (red); a *separate* commit
   updates the case(s) and turns it green, naming which case(s) changed and
   why in one sentence.
2. Every changed line needs a reason, not a re-run. Never regenerate all
   cases from build()'s live output and diff them in bulk -- that is
   exactly the failure mode this file exists to catch. Edit by hand: open
   the specific case(s) the new feature touches, change only those lines,
   leave every other line byte-identical. A case nobody meant to touch
   changing is a regression signal -- stop and find out why before
   accepting it.
3. Cases are formatted one argument per line on purpose: a diff on a
   one-flag-per-line list shows exactly which argument moved.
4. A new dimension (new encoder, new ConversionRequest field, new branch)
   gets new Case entries, not edits to existing ones -- existing cases keep
   asserting exactly what they always asserted, including the default value
   of the new field/branch.

See src/pro/ARCHITECTURE.md's "Golden master protocol" section for the
narrative version of this rule and why it exists.
"""
