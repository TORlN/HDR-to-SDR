def _req(**overrides) -> ConversionRequest:
    base = dict(input_path='in.mp4', output_path='out.mkv', gamma=1.0,
                use_gpu=False, open_after_conversion=False)
    base.update(overrides)
    return ConversionRequest(**base)


def zscale_filter(gamma: float, tonemapper: str) -> str:
    """The CPU (non-libplacebo) tonemap filter body, same call the real
    zscale path in construct_ffmpeg_command makes."""
    return FFMPEG_CONVERT_FILTER.format(gamma=gamma, tonemapper=tonemapper,
                                        lut_path=get_lut_filter_path())


def libplacebo_filter(gamma: float, tonemapper: str, cuda_input: bool,
                      lut_enabled: bool) -> str:
    """The GPU (libplacebo) tonemap filter body, same call the real
    libplacebo path in construct_ffmpeg_command makes."""
    return build_libplacebo_filter(gamma, tonemapper, cuda_input=cuda_input,
                                   lut_enabled=lut_enabled)


def _FC(inner: str) -> str:
    """The [0:v:0]...[vout] frame construct_ffmpeg_command always wraps the
    tonemap filter body in."""
    return f'[0:v:0]{inner}[vout]'


