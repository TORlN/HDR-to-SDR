class TestFfmpegCommandGoldenMaster(unittest.TestCase):
    """One case per branch of construct_ffmpeg_command as it exists before
    the item-6 split (audit item 6). Every case here must stay green
    throughout Tasks 2-7 -- it is what proves the split is behavior-
    preserving. See the module docstring for the edit rules."""

    def _run(self, case: Case) -> None:
        manager = ConversionManager()
        if case.gpu_encoder is not None:
            manager._gpu_encoder = case.gpu_encoder
        if case.gpu_probe_forbidden:
            def _forbidden():
                raise AssertionError(
                    f'{case.name}: detect_gpu_encoder must not be called -- '
                    f'a 12-bit request forces use_gpu off before the GPU '
                    f'vendor probe would run')
            manager.detect_gpu_encoder = _forbidden  # type: ignore[method-assign]
        request = _req(**case.request_kwargs)
        properties = dict(_PROPS, **case.props_kwargs)
        view = RecordingConversionView()
        with patch('src.conversion.platform.system', return_value=case.platform), \
             patch('src.conversion.vulkan_libplacebo_available', return_value=case.libplacebo), \
             patch('src.conversion.vulkan_cuda_interop_available', return_value=case.interop):
            if case.expect_raises is not None:
                with self.assertRaises(ValueError, msg=case.name) as ctx:
                    manager.construct_ffmpeg_command(request, properties, view)
                self.assertEqual(str(ctx.exception), case.expect_raises, msg=case.name)
            else:
                cmd = manager.construct_ffmpeg_command(request, properties, view)
                self.assertEqual(cmd, case.expect, msg=case.name)
        self.assertEqual(len(view.notices), case.expect_notices, msg=case.name)

    def test_golden_cases(self) -> None:
        for case in CASES:
            with self.subTest(case=case.name):
                self._run(case)

    def test_every_case_name_is_unique(self) -> None:
        names = [c.name for c in CASES]
        self.assertEqual(len(names), len(set(names)),
                         msg='duplicate case name -- subTest would silently '
                             'merge two different cases under one label')


if __name__ == '__main__':
    unittest.main()
